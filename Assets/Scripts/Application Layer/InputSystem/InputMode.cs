/// <summary>
/// 입력이 지금 게임플레이로 가는지 UI로 가는지입니다.
///
/// 패드 때문에 필요해진 개념입니다. 마우스 시절에는 "커서가 UI 위에 있는가"로 구분할 수 있었지만
/// (InputManager.SetCursorHoveredOnUI), 패드에는 커서가 없어서 그 판단 기준 자체가 성립하지 않습니다.
/// 예를 들어 A 버튼은 UI에서는 "확인"이고 게임에서는 "상호작용"이라, 팝업을 확인하려고 A를 누르면
/// 뒤에서 캐릭터가 같이 상호작용해 버립니다.
///
/// UI 모드에서도 막지 않는 것이 있습니다.
/// - ESC/Start: 메뉴를 닫는 키라서 UI 모드에서 막으면 창에서 나갈 수 없게 됩니다.
/// - 인벤토리 키: 같은 키로 열고 닫으므로 막으면 닫히지 않습니다.
/// - 버튼을 뗄 때(release/canceled): 누른 뒤 UI 모드로 바뀌면 뗀 신호가 사라져
///   공격이 눌린 채로 남습니다. 떼는 신호는 언제나 통과시킵니다.
/// </summary>
public enum EInputMode
{
    Gameplay = 0,
    UI = 1,
}
